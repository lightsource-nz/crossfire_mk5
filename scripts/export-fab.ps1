# Produces everything a fabricator's quote and assembly order take, from the board as it is: the
# Gerbers and drill files zipped for upload, the bill of materials with the fabricator's catalogue
# column, and the placement file in the column names the fabricator's uploader expects.
#
# The rules check runs first, with schematic parity, and nothing is written if it reports a
# violation: files from a board that fails its own check are not files to send anywhere. The
# check refills the pours and saves the board before it looks, because the Gerbers are plotted
# from the fill stored in the file, and a fill saved before the last edit is a fill that is wrong.
# So this writes the board file, with KiCad closed, and only ever changes its pours.
#
# Output goes to pcb/fab/, which is not tracked: every file in it is derived from the board and the
# schematic, and regenerated by running this again.
#
# USAGE:  scripts/export-fab.ps1 [-SkipDrc]
param([switch]$SkipDrc)
$ErrorActionPreference = 'Stop'

$cli = $null
foreach ($base in @("$env:ProgramFiles\KiCad", "${env:ProgramFiles(x86)}\KiCad")) {
	if (-not (Test-Path $base)) { continue }
	foreach ($ver in (Get-ChildItem $base -Directory | Sort-Object Name -Descending)) {
		$candidate = Join-Path $ver.FullName 'bin\kicad-cli.exe'
		if (Test-Path $candidate) { $cli = $candidate; break }
	}
	if ($cli) { break }
}
if (-not $cli) { throw "could not find kicad-cli -- KiCad ships it at <KiCad>\bin\kicad-cli.exe" }

$pcbDir = Join-Path (Split-Path $PSScriptRoot -Parent) 'pcb'
$board  = Join-Path $pcbDir 'crossfire.kicad_pcb'
$sch    = Join-Path $pcbDir 'crossfire.kicad_sch'
$out    = Join-Path $pcbDir 'fab'
$gerb   = Join-Path $out 'gerbers'
New-Item -ItemType Directory -Force $out, $gerb | Out-Null
Get-ChildItem $gerb -File | Remove-Item -Force

if (Get-Process kicad, eeschema, pcbnew -ErrorAction SilentlyContinue) {
	throw "close KiCad first: the check refills the pours and saves the board"
}
if (-not $SkipDrc) {
	$report = Join-Path $out 'drc.rpt'
	& $cli pcb drc --schematic-parity --severity-error --severity-warning --refill-zones --save-board -o $report $board | Out-Null
	$summary = Get-Content $report | Select-String '^\*\* Found'
	$summary | ForEach-Object { $_.Line }
	if ($summary | Where-Object { $_.Line -notmatch 'Found 0 ' }) {
		throw "the rules check reports something; see $report"
	}
}

& $cli pcb export gerbers --board-plot-params --subtract-soldermask -o "$gerb\" $board | Out-Null
& $cli pcb export drill --format excellon --excellon-units mm --generate-map --map-format gerberx2 -o "$gerb\" $board | Out-Null
$zip = Join-Path $out 'crossfire-gerbers.zip'
if (Test-Path $zip) { Remove-Item $zip -Force }
Compress-Archive -Path "$gerb\*" -DestinationPath $zip

#   the bill of materials, one row per part, with the fabricator's catalogue number where the
# schematic carries one; rows without one are matched in the fabricator's tool at order time.
#   The footprint column is rewritten to the plain package code the fabricator's tool reads:
# KiCad's name carries both sizes, "C_0402_1005Metric", and the tool takes the one beside
# "Metric", which in imperial is 01005 -- a quarter the part -- so it matched and rendered the
# passives at a quarter of their size until the column said just "0402".
$bomRaw = Join-Path $out 'crossfire-bom-kicad.csv'
& $cli sch export bom `
	--fields 'Reference,Value,Footprint,MPN,LCSC,Sourcing' `
	--labels 'Designator,Comment,Footprint,MPN,LCSC Part #,Sourcing' `
	--group-by 'Value,Footprint,LCSC' --ref-range-delimiter '' --exclude-dnp `
	-o $bomRaw $sch | Out-Null
Import-Csv $bomRaw | ForEach-Object {
	$fp = $_.Footprint -replace '^[^:]+:', ''
	if ($fp -match '^(?:C|R|L|LED|D)_(\d{4})_\d{4}Metric') { $fp = $Matches[1] }
	elseif ($fp -match '^(QFN-\d+)') { $fp = $Matches[1] }
	elseif ($fp -match '^(SOIC-\d+)') { $fp = $Matches[1] }
	$_.Footprint = $fp
	$_
} | Export-Csv -NoTypeInformation -Path (Join-Path $out 'crossfire-bom.csv')
Remove-Item $bomRaw -Force

#   the placement file, written by cpl.py beside this script: the fabricator's columns, each
# part at the centre of its pad pattern rather than at its footprint's anchor, in the Gerbers'
# own frame. KiCad's own export gives the anchor, which put the USB-C receptacle a body-width off
# its pads in the fabricator's preview.
$python = $null
foreach ($base in @("$env:ProgramFiles\KiCad", "${env:ProgramFiles(x86)}\KiCad")) {
	if (-not (Test-Path $base)) { continue }
	foreach ($ver in (Get-ChildItem $base -Directory | Sort-Object Name -Descending)) {
		$candidate = Join-Path $ver.FullName 'bin\python.exe'
		if (Test-Path $candidate) { $python = $candidate; break }
	}
	if ($python) { break }
}
if (-not $python) { throw "could not find KiCad's Python -- it ships at <KiCad>\bin\python.exe" }
$placed = & $python (Join-Path $PSScriptRoot 'cpl.py') $board (Join-Path $out 'crossfire-cpl.csv') 2>&1 |
	Where-Object { $_ -notmatch 'swig|image handler|assert' }

"wrote $zip"
"wrote crossfire-bom.csv and crossfire-cpl.csv ($placed) in $out"
